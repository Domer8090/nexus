import fs from "node:fs";
import path from "node:path";
import { run } from "./proc";

/**
 * Project map: one Markdown file that lists every source file with its size and what it exports,
 * so an agent reads one file instead of listing folders and opening files to find its way.
 *
 * Built locally from the files themselves (no model). Written as NEXUS_MAP.md at the folder root;
 * in a git checkout it is added to .git/info/exclude so it never shows up in a diff or gets applied.
 */

export const MAP_FILE = "NEXUS_MAP.md";
const MAX_BYTES = 48_000;
const SKIP_DIRS = new Set(["node_modules", ".git", ".next", "dist", "build", "out", "coverage", ".turbo", ".vercel", "vendor", "target", "__pycache__", ".venv", "venv", ".cache"]);
const TEXT = /\.(tsx?|jsx?|mjs|cjs|py|go|rs|rb|java|kt|swift|c|cc|cpp|h|hpp|cs|php|vue|svelte|astro|css|scss|html?|md|mdx|json|ya?ml|toml|sql|sh|graphql|prisma)$/i;
const LOCK = /(package-lock\.json|pnpm-lock\.yaml|yarn\.lock|bun\.lockb?|Cargo\.lock|poetry\.lock|\.min\.(js|css))$/;

export type MapResult = { text: string; files: number; bytes: number; truncated: boolean };

async function listFiles(dir: string): Promise<string[]> {
  const git = await run("git", ["ls-files", "--cached", "--others", "--exclude-standard"], { cwd: dir, timeoutMs: 20_000 });
  if (git.code === 0 && git.stdout.trim()) return git.stdout.split("\n").filter(Boolean);
  const out: string[] = [];
  const walk = (rel: string, depth: number) => {
    if (depth > 8 || out.length > 4000) return;
    let entries: fs.Dirent[] = [];
    try {
      entries = fs.readdirSync(path.join(dir, rel), { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      if (e.name.startsWith(".") && e.name !== ".env.example") continue;
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) {
        if (!SKIP_DIRS.has(e.name)) walk(r, depth + 1);
      } else if (e.isFile()) out.push(r);
    }
  };
  walk("", 0);
  return out;
}

/** The names a file defines, read with simple patterns per language. */
export function symbols(file: string, src: string): string[] {
  const out: string[] = [];
  const add = (re: RegExp) => {
    for (const m of src.matchAll(re)) if (m[1] && !out.includes(m[1])) out.push(m[1]);
  };
  if (/\.(tsx?|jsx?|mjs|cjs|vue|svelte|astro)$/.test(file)) {
    add(/^export\s+(?:default\s+)?(?:async\s+)?(?:function\*?|class|const|let|type|interface|enum)\s+([A-Za-z_$][\w$]*)/gm);
    if (/^export\s+default\s/m.test(src) && !out.length) out.push("default");
  } else if (/\.py$/.test(file)) add(/^(?:async\s+)?(?:def|class)\s+([A-Za-z_]\w*)/gm);
  else if (/\.go$/.test(file)) add(/^func\s+(?:\([^)]*\)\s*)?([A-Z]\w*)/gm);
  else if (/\.rs$/.test(file)) add(/^pub\s+(?:async\s+)?(?:fn|struct|enum|trait)\s+(\w+)/gm);
  else if (/\.(css|scss)$/.test(file)) add(/^\s*(--[\w-]+)\s*:/gm);
  else if (/\.(md|mdx)$/.test(file)) add(/^#{1,2}\s+(.+)$/gm);
  return out.slice(0, 14);
}

/** First line of a leading doc comment, if the file has one. */
export function purpose(src: string): string | null {
  const m = src.match(/^\s*(?:"use (?:client|server)";?\s*)?(?:import[^\n]*\n|\s)*?\/\*\*?\s*\n?\s*\*?\s*([^\n*][^\n]{8,160})/) ?? src.match(/^\s*(?:#|\/\/)\s*([^\n!][^\n]{8,160})/) ?? src.match(/^\s*"""\s*([^\n]{8,160})/);
  return m ? m[1].trim().replace(/\s*\*\/$/, "") : null;
}

export async function buildMap(dir: string): Promise<MapResult> {
  const all = (await listFiles(dir)).filter((f) => !f.endsWith(MAP_FILE) && !LOCK.test(f) && !f.split("/").some((seg) => SKIP_DIRS.has(seg)));
  const head: string[] = [`# Project map: ${path.basename(dir)}`, "", "Generated by Nexus from the files on disk. Read this first; open only the files you need. Sizes are line counts.", ""];
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8")) as { name?: string; scripts?: Record<string, string>; dependencies?: Record<string, string>; devDependencies?: Record<string, string> };
    head.push("## package.json", "");
    if (pkg.name) head.push(`- name: ${pkg.name}`);
    if (pkg.scripts) head.push(`- scripts: ${Object.entries(pkg.scripts).map(([k, v]) => `${k} (\`${v.slice(0, 60)}\`)`).join(", ")}`);
    const deps = Object.keys({ ...pkg.dependencies });
    const dev = Object.keys({ ...pkg.devDependencies });
    if (deps.length) head.push(`- dependencies: ${deps.join(", ")}`);
    if (dev.length) head.push(`- devDependencies: ${dev.join(", ")}`);
    head.push("");
  } catch {}

  const byDir = new Map<string, string[]>();
  let mapped = 0;
  for (const f of all.sort()) {
    const abs = path.join(dir, f);
    let st: fs.Stats;
    try {
      st = fs.statSync(abs);
    } catch {
      continue;
    }
    if (!st.isFile()) continue;
    const d = path.dirname(f) === "." ? "(root)" : path.dirname(f);
    let line = `- \`${path.basename(f)}\``;
    if (TEXT.test(f) && st.size < 400_000) {
      const src = fs.readFileSync(abs, "utf8");
      const lines = src.split("\n").length;
      const what = purpose(src);
      const syms = symbols(f, src);
      line += ` ${lines}L`;
      if (what) line += ` — ${what}`;
      if (syms.length) line += ` [${syms.join(", ")}]`;
    } else line += ` (${Math.round(st.size / 1024)} KB)`;
    if (!byDir.has(d)) byDir.set(d, []);
    byDir.get(d)!.push(line);
    mapped++;
  }
  const body: string[] = ["## Files", ""];
  for (const [d, lines] of byDir) body.push(`### ${d}/`, ...lines, "");
  let text = [...head, ...body].join("\n");
  let truncated = false;
  if (Buffer.byteLength(text) > MAX_BYTES) {
    text = text.slice(0, MAX_BYTES).replace(/\n[^\n]*$/, "") + "\n\n(Map cut off at 48 KB. Large folders at the end are not listed; list them only if you need them.)\n";
    truncated = true;
  }
  return { text, files: mapped, bytes: Buffer.byteLength(text), truncated };
}

/** Keeps the map out of git: adds it to info/exclude of the repository (shared by worktrees). */
async function excludeFromGit(dir: string) {
  const r = await run("git", ["rev-parse", "--git-common-dir"], { cwd: dir, timeoutMs: 10_000 });
  if (r.code !== 0) return false;
  const common = path.resolve(dir, r.stdout.trim());
  const file = path.join(common, "info", "exclude");
  try {
    const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    if (!cur.split("\n").includes(`/${MAP_FILE}`)) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.appendFileSync(file, `${cur.endsWith("\n") || !cur ? "" : "\n"}# Nexus project map\n/${MAP_FILE}\n`);
    }
    return true;
  } catch {
    return false;
  }
}

/** Writes NEXUS_MAP.md into a folder. Only in a git checkout, where it can be kept out of the diff. */
export async function writeMap(dir: string): Promise<(MapResult & { path: string }) | { error: string }> {
  if (!(await excludeFromGit(dir))) return { error: "Not a git repository, so Nexus can't keep the map out of your changes." };
  const m = await buildMap(dir);
  const p = path.join(dir, MAP_FILE);
  fs.writeFileSync(p, m.text);
  return { ...m, path: p };
}

